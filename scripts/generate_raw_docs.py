def slugify_filename(entity_id: str) -> str:
    return re.sub(r"[^a-z0-9_]", "", entity_id.lower())


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    index = []
    for ent in ENTITIES:
        filename = f"{ent['id']}.md"
        path = os.path.join(OUTPUT_DIR, filename)
        content = (
            f"# {ent['term']}\n\n"
            f"Категория: {ent['category']}\n\n"
            f"{ent['text']}\n"
        )
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        index.append({"file": filename, "term": ent["term"], "category": ent["category"]})

    with open(os.path.join(OUTPUT_DIR, "_index.json"), "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=2)

    print(f"Создано документов: {len(ENTITIES)}")
    print(f"Папка: {os.path.abspath(OUTPUT_DIR)}")


if __name__ == "__main__":
    main()
